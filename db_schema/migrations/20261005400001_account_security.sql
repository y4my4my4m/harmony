-- Account security: two-factor enforcement in the database, recovery codes generated and
-- rate-limited server-side, session listing and revocation, security notices, data export,
-- and account deletion that re-authenticates and federates a Delete for the actor.
--
-- Assurance. GoTrue issues an aal1 session for a correct password before the TOTP
-- challenge, and PostgREST accepted it: the second factor gated the web UI only. GoTrue
-- v2.182.1 keeps a session at aal2 once a factor is verified and deletes the account's
-- other aal1 sessions on every successful verify, so a legitimate session of an enrolled
-- account is aal2. An aal1 one is mid-challenge or a password-only client.
--   session_meets_aal()            false for an authenticated request of an account with a
--                                  verified factor whose token is not aal2.
--   enforce_request_assurance()    PostgREST db-pre-request. 401 session_revoked when the
--                                  token's session_id no longer exists in auth.sessions;
--                                  403 insufficient_aal when session_meets_aal() is false.
--                                  /rpc/redeem_recovery_code_and_disable_mfa stays open.
--   restrictive policies           public.messages SELECT (postgres_changes),
--                                  realtime.messages (private channels), storage.objects.
--                                  The paths that bypass PostgREST.
-- pgrst.db_pre_request is set on the authenticator role and read on 'reload config'.
-- Dropping enforce_request_assurance() while the setting names it fails every request.
--
-- Recovery codes. Ten codes of ten Crockford base32 characters (50 bits), generated by
-- generate_mfa_recovery_codes() at aal2 within ten minutes of a TOTP verify, returned once,
-- stored as SHA-256 of the normalised code. Normalisation strips separators, upper-cases and
-- maps O->0, I/L->1; codes issued before this file are upper-case hex and normalise to
-- themselves. Five failed codes per account per fifteen minutes, then PT429. A verified
-- factor's removal deletes the account's codes.
--
-- Sessions. list_my_sessions() and revoke_my_session() read and delete the caller's
-- auth.sessions rows; refresh tokens cascade. push_subscriptions.session_id is written by
-- the federation backend at subscribe time, and a deleted session takes its push rows.
--
-- Security notices. Triggers on auth.sessions, auth.mfa_factors and auth.users insert
-- notifications of type 'security': a sign-in while another session exists, 2FA enabled or
-- disabled, password changed. Recovery-code use and regeneration notify from the RPCs. Each
-- trigger swallows its own errors so a GoTrue write never fails on account of a notice.
--
-- Export. request_my_data_export() returns everything except messages and records an export
-- valid for an hour; export_my_messages() pages the caller's own messages under it. Ten
-- minutes between exports, five per day. Key material, hashes, tokens and push endpoints
-- are not exported; DMs carry the caller's own messages and participant handles only.
--
-- Ownership. Every function defined here is owned by postgres, as on a fresh install. Run
-- as supabase_admin, CREATE leaves new functions owned by supabase_admin and CREATE OR
-- REPLACE keeps an existing function's owner, so a postgres-owned definer would call a
-- supabase_admin-owned helper whose PUBLIC grant is revoked (42501). New tables are owned
-- by postgres. The tables the definers read and write are checked for the privileges
-- postgres needs; missing ones are granted and the migration fails if a grant does not
-- take. mfa_recovery_codes is reachable through these functions only: no client or
-- service_role grant, as on production.
--
-- Deletion. delete_my_account(p_password) checks the password against auth.users with
-- pgcrypto (bcrypt, $2a$), five failures per fifteen minutes, shared with
-- verify_my_password() which gates the password-change form; accounts without a password
-- need a sign-in within ten minutes; enrolled accounts need a TOTP verify within ten
-- minutes. Content stays, attributed to the tombstoned profile (deleted_at set). The actor's
-- key, URI and the inboxes of its remote followers and followees go to deleted_actors and an
-- 'account-deleted' job sends the Delete and removes avatar and banner objects. Bots are
-- deactivated and their tokens revoked. The zero-argument delete_my_account() is replaced:
-- a call without a password answers password_required.

BEGIN;

