-- The caller's own messages, oldest first, keyset-paged on (created_at, id). System
-- messages attributed to the caller (joins, calls) are not exported.
CREATE OR REPLACE FUNCTION public.export_my_messages(
    p_export_id uuid,
    p_after_created_at timestamptz DEFAULT NULL,
    p_after_id uuid DEFAULT NULL,
    p_limit integer DEFAULT 1000)
RETURNS jsonb
LANGUAGE plpgsql
STABLE
SECURITY DEFINER
SET search_path = pg_catalog, public, pg_temp
AS $$
DECLARE
    v_profile uuid := public.get_current_profile_id();
    v_limit integer := least(greatest(coalesce(p_limit, 1000), 1), 2000);
    v_rows jsonb;
BEGIN
    IF v_profile IS NULL THEN
        RAISE EXCEPTION 'Authentication required' USING ERRCODE = '42501';
    END IF;
    IF NOT EXISTS (SELECT 1 FROM public.account_data_exports e
                    WHERE e.id = p_export_id AND e.profile_id = v_profile AND e.expires_at > now()) THEN
        RAISE SQLSTATE 'PT410' USING MESSAGE = 'export_expired',
            HINT = 'Request a new export.';
    END IF;

    WITH page AS (
        SELECT m.id, m.created_at, m.updated_at, m.channel_id, m.conversation_id, m.thread_id,
               m.reply_to, m.content, m.encrypted, m.is_deleted, m.is_pinned
          FROM public.messages m
         WHERE m.user_id = v_profile
           AND m.is_system IS NOT TRUE
           AND (p_after_created_at IS NULL
                OR (m.created_at, m.id) > (p_after_created_at, coalesce(p_after_id, '00000000-0000-0000-0000-000000000000'::uuid)))
         ORDER BY m.created_at, m.id
         LIMIT v_limit
    )
    SELECT coalesce(jsonb_agg(jsonb_build_object(
               'id', pg.id, 'created_at', pg.created_at, 'updated_at', pg.updated_at,
               'server_id', ch.server_id, 'server_name', sv.name,
               'channel_id', pg.channel_id, 'channel_name', ch.name,
               'conversation_id', pg.conversation_id, 'thread_id', pg.thread_id,
               'reply_to', pg.reply_to, 'content', pg.content, 'encrypted', pg.encrypted,
               'is_deleted', pg.is_deleted, 'is_pinned', pg.is_pinned)
               ORDER BY pg.created_at, pg.id), '[]'::jsonb)
      INTO v_rows
      FROM page pg
      LEFT JOIN public.channels ch ON ch.id = pg.channel_id
      LEFT JOIN public.servers sv ON sv.id = ch.server_id;

    IF jsonb_array_length(v_rows) < v_limit THEN
        RETURN jsonb_build_object('messages', v_rows, 'next', NULL);
    END IF;
    RETURN jsonb_build_object('messages', v_rows, 'next', jsonb_build_object(
        'created_at', v_rows -> -1 -> 'created_at', 'id', v_rows -> -1 -> 'id'));
END;
$$;

