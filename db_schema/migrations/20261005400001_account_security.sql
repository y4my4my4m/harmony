CREATE OR REPLACE FUNCTION public.on_auth_mfa_factor_changed()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = pg_catalog, public, pg_temp
AS $$
BEGIN
    IF TG_OP = 'UPDATE' THEN
        IF NEW.status::text = 'verified' AND OLD.status::text IS DISTINCT FROM 'verified' THEN
            PERFORM public.record_security_notice(NEW.user_id, 'mfa_enabled',
                jsonb_build_object('factor_type', NEW.factor_type::text));
        END IF;
    ELSIF OLD.status::text = 'verified' AND NOT public.mfa_enabled_for(OLD.user_id) THEN
        DELETE FROM public.mfa_recovery_codes r
         WHERE r.user_id = OLD.user_id
            OR r.user_id IN (SELECT p.id FROM public.profiles p WHERE p.auth_user_id = OLD.user_id);
        PERFORM public.record_security_notice(OLD.user_id, 'mfa_disabled', jsonb_build_object(
            'factor_type', OLD.factor_type::text,
            'reason', nullif(current_setting('harmony.mfa_disable_reason', true), '')));
    END IF;
    RETURN NULL;
EXCEPTION WHEN OTHERS THEN
    RAISE WARNING 'on_auth_mfa_factor_changed: %', SQLERRM;
    RETURN NULL;
END;
$$;

