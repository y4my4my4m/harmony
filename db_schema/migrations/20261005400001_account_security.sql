-- Raises PT429 once five checks of p_kind failed inside fifteen minutes. DETAIL carries
-- retry_after=<seconds>.
CREATE OR REPLACE FUNCTION public.assert_security_attempt_budget(p_auth_user_id uuid, p_kind text)
RETURNS void
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = pg_catalog, public, pg_temp
AS $$
DECLARE
    v_failures integer;
    v_oldest timestamptz;
BEGIN
    SELECT count(*), min(a.attempted_at) INTO v_failures, v_oldest
      FROM public.account_security_attempts a
     WHERE a.auth_user_id = p_auth_user_id
       AND a.kind = p_kind
       AND NOT a.succeeded
       AND a.attempted_at > now() - interval '15 minutes';

    IF v_failures >= 5 THEN
        RAISE SQLSTATE 'PT429' USING
            MESSAGE = 'too_many_attempts',
            DETAIL = 'retry_after=' || greatest(1, ceil(extract(epoch FROM
                         v_oldest + interval '15 minutes' - now())))::bigint;
    END IF;
END;
$$;

CREATE OR REPLACE FUNCTION public.record_security_attempt(p_auth_user_id uuid, p_kind text, p_succeeded boolean)
RETURNS void
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = pg_catalog, public, pg_temp
AS $$
BEGIN
    DELETE FROM public.account_security_attempts a
     WHERE a.auth_user_id = p_auth_user_id AND a.attempted_at < now() - interval '1 day';
    INSERT INTO public.account_security_attempts (auth_user_id, kind, succeeded)
    VALUES (p_auth_user_id, p_kind, p_succeeded);
END;
$$;

-- Notification of type 'security' for the live profile of an auth user. data.event is one
-- of new_sign_in, mfa_enabled, mfa_disabled, recovery_code_used,
-- recovery_codes_regenerated, password_changed.
CREATE OR REPLACE FUNCTION public.record_security_notice(p_auth_user_id uuid, p_event text, p_data jsonb DEFAULT '{}'::jsonb)
RETURNS void
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = pg_catalog, public, pg_temp
AS $$
BEGIN
    INSERT INTO public.notifications (user_id, type, data)
    SELECT p.id, 'security',
           jsonb_build_object('event', p_event, 'at', now()) || coalesce(p_data, '{}'::jsonb)
      FROM public.profiles p
     WHERE p.auth_user_id = p_auth_user_id
       AND p.deleted_at IS NULL
     LIMIT 1;
END;
$$;

