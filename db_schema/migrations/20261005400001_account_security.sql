-- GoTrue creates sessions and mfa_factors at service start; a bare Postgres image has
-- neither. One block per table so a privilege failure on one leaves the others installed.
DO $$
BEGIN
    IF to_regclass('auth.sessions') IS NULL THEN
        RAISE NOTICE 'auth.sessions absent, session triggers skipped';
        RETURN;
    END IF;
    DROP TRIGGER IF EXISTS harmony_session_created ON auth.sessions;
    CREATE TRIGGER harmony_session_created AFTER INSERT ON auth.sessions
        FOR EACH ROW EXECUTE FUNCTION public.on_auth_session_created();
    DROP TRIGGER IF EXISTS harmony_session_deleted ON auth.sessions;
    CREATE TRIGGER harmony_session_deleted AFTER DELETE ON auth.sessions
        FOR EACH ROW EXECUTE FUNCTION public.on_auth_session_deleted();
    RAISE NOTICE 'auth.sessions triggers installed';
EXCEPTION WHEN insufficient_privilege THEN
    RAISE NOTICE 'auth.sessions triggers skipped: %', SQLERRM;
END;
$$;

DO $$
BEGIN
    IF to_regclass('auth.mfa_factors') IS NULL THEN
        RAISE NOTICE 'auth.mfa_factors absent, factor triggers skipped';
        RETURN;
    END IF;
    DROP TRIGGER IF EXISTS harmony_mfa_factor_verified ON auth.mfa_factors;
    CREATE TRIGGER harmony_mfa_factor_verified AFTER UPDATE OF status ON auth.mfa_factors
        FOR EACH ROW EXECUTE FUNCTION public.on_auth_mfa_factor_changed();
    DROP TRIGGER IF EXISTS harmony_mfa_factor_deleted ON auth.mfa_factors;
    CREATE TRIGGER harmony_mfa_factor_deleted AFTER DELETE ON auth.mfa_factors
        FOR EACH ROW EXECUTE FUNCTION public.on_auth_mfa_factor_changed();
    RAISE NOTICE 'auth.mfa_factors triggers installed';
EXCEPTION WHEN insufficient_privilege THEN
    RAISE NOTICE 'auth.mfa_factors triggers skipped: %', SQLERRM;
END;
$$;

DO $$
BEGIN
    DROP TRIGGER IF EXISTS harmony_password_changed ON auth.users;
    CREATE TRIGGER harmony_password_changed AFTER UPDATE OF encrypted_password ON auth.users
        FOR EACH ROW
        WHEN (OLD.encrypted_password IS DISTINCT FROM NEW.encrypted_password
              AND coalesce(OLD.encrypted_password, '') <> '')
        EXECUTE FUNCTION public.on_auth_password_changed();
    RAISE NOTICE 'auth.users password trigger installed';
EXCEPTION WHEN insufficient_privilege THEN
    RAISE NOTICE 'auth.users password trigger skipped: %', SQLERRM;
END;
$$;

