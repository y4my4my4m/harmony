RETURNS jsonb
LANGUAGE sql
STABLE
SET search_path = pg_catalog, pg_temp
AS $$
    SELECT nullif(current_setting('request.jwt.claims', true), '')::jsonb;
$$;

CREATE OR REPLACE FUNCTION public.mfa_enabled_for(p_auth_user_id uuid)
RETURNS boolean
LANGUAGE plpgsql
STABLE
SECURITY DEFINER
SET search_path = pg_catalog, public, pg_temp
AS $$
BEGIN
    IF p_auth_user_id IS NULL OR to_regclass('auth.mfa_factors') IS NULL THEN
        RETURN false;
    END IF;
    RETURN EXISTS (SELECT 1 FROM auth.mfa_factors f
                    WHERE f.user_id = p_auth_user_id AND f.status = 'verified');
END;
$$;

-- request.jwt.claims carries role; the test harness sets only the role GUC, which a
-- SECURITY DEFINER body still reads as the session's SET ROLE.
CREATE OR REPLACE FUNCTION public.session_meets_aal()
RETURNS boolean
LANGUAGE plpgsql
STABLE
SECURITY DEFINER
SET search_path = pg_catalog, public, pg_temp
AS $$
DECLARE
    v_claims jsonb := public.current_jwt_claims();
    v_role text;
BEGIN
    v_role := coalesce(v_claims ->> 'role', nullif(current_setting('role', true), 'none'));
    IF v_role IS DISTINCT FROM 'authenticated' OR v_claims ->> 'aal' = 'aal2' THEN
        RETURN true;
    END IF;
    RETURN NOT public.mfa_enabled_for(auth.uid());
END;
$$;

-- True when the token's amr lists p_method (any method when NULL) authenticated within
-- p_max_age. GoTrue writes amr as [{method, timestamp}] with timestamp in epoch seconds.
CREATE OR REPLACE FUNCTION public.session_step_up_fresh(p_method text, p_max_age interval)
RETURNS boolean
LANGUAGE sql
STABLE
SET search_path = pg_catalog, public, pg_temp
AS $$
    SELECT EXISTS (
        SELECT 1
          FROM jsonb_array_elements(
                 CASE WHEN jsonb_typeof(public.current_jwt_claims() -> 'amr') = 'array'
                      THEN public.current_jwt_claims() -> 'amr' ELSE '[]'::jsonb END) e
         WHERE jsonb_typeof(e) = 'object'
           AND (p_method IS NULL OR e ->> 'method' = p_method)
           AND (e ->> 'timestamp') ~ '^[0-9]+$'
           AND (e ->> 'timestamp')::bigint >= extract(epoch FROM now() - p_max_age)::bigint
    );
$$;

CREATE OR REPLACE FUNCTION public.enforce_request_assurance()
RETURNS void
LANGUAGE plpgsql
STABLE
SECURITY DEFINER
SET search_path = pg_catalog, public, pg_temp
AS $$
DECLARE
    v_claims jsonb := public.current_jwt_claims();
    v_sid text;
BEGIN
    IF v_claims IS NULL OR v_claims ->> 'role' IS DISTINCT FROM 'authenticated' THEN
        RETURN;
    END IF;

    v_sid := v_claims ->> 'session_id';
    IF v_sid ~* '^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$'
       AND to_regclass('auth.sessions') IS NOT NULL
       AND NOT EXISTS (SELECT 1 FROM auth.sessions s WHERE s.id = v_sid::uuid) THEN
        RAISE SQLSTATE 'PT401' USING
            MESSAGE = 'session_revoked',
            HINT = 'This session was signed out. Sign in again.';
    END IF;

    IF public.session_meets_aal()
       OR current_setting('request.path', true) = '/rpc/redeem_recovery_code_and_disable_mfa' THEN
        RETURN;
    END IF;

    RAISE SQLSTATE 'PT403' USING
        MESSAGE = 'insufficient_aal',
        DETAIL = 'This account requires two-factor authentication.',
        HINT = 'Complete the two-factor challenge.';
END;
$$;

COMMENT ON FUNCTION public.enforce_request_assurance() IS
    'PostgREST db-pre-request (authenticator: pgrst.db_pre_request). Every PostgREST request fails while the setting names a missing function.';

