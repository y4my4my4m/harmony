-- Self-demotion is not escalation: lowering is_admin or is_moderator while leaving the
-- other moderation flags untouched passes, which account deletion needs for moderators.
CREATE OR REPLACE FUNCTION public.prevent_profile_moderation_self_update()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
DECLARE
    v_role text;
    v_is_admin boolean;
BEGIN
    v_role := current_setting('request.jwt.claims', true)::jsonb ->> 'role';
    IF v_role = 'service_role' OR session_user = 'postgres' THEN
        RETURN NEW;
    END IF;

    IF NEW.is_suspended IS NOT DISTINCT FROM OLD.is_suspended
       AND NEW.is_silenced IS NOT DISTINCT FROM OLD.is_silenced
       AND NEW.force_sensitive IS NOT DISTINCT FROM OLD.force_sensitive
       AND (NEW.is_admin IS NOT DISTINCT FROM OLD.is_admin OR NEW.is_admin IS FALSE)
       AND (NEW.is_moderator IS NOT DISTINCT FROM OLD.is_moderator OR NEW.is_moderator IS FALSE)
    THEN
        RETURN NEW;
    END IF;

    SELECT EXISTS (
        SELECT 1 FROM public.profiles p
        WHERE p.auth_user_id = auth.uid()
          AND p.is_admin = true
          AND COALESCE(p.is_suspended, false) = false
    ) INTO v_is_admin;

    IF v_is_admin IS NOT TRUE THEN
        RAISE EXCEPTION
            'Permission denied: cannot modify moderation flags on profile'
            USING ERRCODE = '42501';
    END IF;

    RETURN NEW;
END;
$$;

-- deleted_at changes only while the same UPDATE detaches the auth user, which
-- profiles_update_own forbids a client from doing. SECURITY INVOKER: current_user is the
-- role issuing the UPDATE.
CREATE OR REPLACE FUNCTION public.protect_profile_deleted_at()
RETURNS trigger
LANGUAGE plpgsql
SET search_path = pg_catalog, public, pg_temp
AS $$
BEGIN
    IF NEW.deleted_at IS DISTINCT FROM OLD.deleted_at
       AND NEW.auth_user_id IS NOT NULL
       AND current_user IN ('anon', 'authenticated') THEN
        RAISE EXCEPTION 'deleted_at is set by account deletion only' USING ERRCODE = '42501';
    END IF;
    RETURN NEW;
END;
$$;
REVOKE ALL ON FUNCTION public.protect_profile_deleted_at() FROM PUBLIC, anon, authenticated;

DROP TRIGGER IF EXISTS protect_profile_deleted_at_trigger ON public.profiles;
CREATE TRIGGER protect_profile_deleted_at_trigger
    BEFORE UPDATE OF deleted_at ON public.profiles
    FOR EACH ROW EXECUTE FUNCTION public.protect_profile_deleted_at();

-- Profile federation stays silent for a tombstone; the Delete covers it.
CREATE OR REPLACE FUNCTION public.trigger_queue_profile_federation()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
BEGIN
    IF NEW.is_local != true OR NEW.deleted_at IS NOT NULL THEN
        RETURN NEW;
    END IF;

    IF TG_OP = 'UPDATE' THEN
        IF (
            OLD.display_name IS NOT DISTINCT FROM NEW.display_name AND
            OLD.bio IS NOT DISTINCT FROM NEW.bio AND
            OLD.avatar_url IS NOT DISTINCT FROM NEW.avatar_url AND
            OLD.banner_url IS NOT DISTINCT FROM NEW.banner_url AND
            OLD.custom_status IS NOT DISTINCT FROM NEW.custom_status
        ) THEN
            RETURN NEW;
        END IF;
    END IF;

    PERFORM public.queue_federation_job(
        'federate-profile',
        jsonb_build_object(
            'type', CASE WHEN TG_OP = 'INSERT' THEN 'create' ELSE 'update' END,
            'profile_id', NEW.id,
            'username', NEW.username,
            'display_name', NEW.display_name,
            'bio', NEW.bio,
            'avatar_url', NEW.avatar_url,
            'banner_url', NEW.banner_url,
            'custom_status', NEW.custom_status
        ),
        3, 5, 3600
    );

    RETURN NEW;
END;
$$;

