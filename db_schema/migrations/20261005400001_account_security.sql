DO $$
DECLARE
    fn regprocedure;
BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'postgres') THEN
        RAISE NOTICE 'postgres role absent, ownership left with %', current_user;
        RETURN;
    END IF;
    FOR fn IN
        SELECT p.oid::regprocedure
          FROM pg_proc p
         WHERE p.pronamespace = 'public'::regnamespace
           AND p.proname IN (
               'current_jwt_claims', 'mfa_enabled_for', 'session_meets_aal',
               'session_step_up_fresh', 'enforce_request_assurance',
               'assert_security_attempt_budget', 'record_security_attempt',
               'record_security_notice', 'verify_my_password', 'normalize_recovery_code',
               'hash_recovery_code', 'recovery_code_owner', 'generate_mfa_recovery_codes',
               'get_mfa_recovery_status', 'save_recovery_codes', 'verify_recovery_code',
               'redeem_recovery_code_and_disable_mfa', 'list_my_sessions', 'revoke_my_session',
               'on_auth_session_created', 'on_auth_session_deleted',
               'on_auth_mfa_factor_changed', 'on_auth_password_changed', 'profile_handle',
               'request_my_data_export', 'export_my_messages',
               'prevent_profile_moderation_self_update', 'protect_profile_deleted_at',
               'trigger_queue_profile_federation', 'delete_my_account')
           AND pg_get_userbyid(p.proowner) <> 'postgres'
    LOOP
        EXECUTE format('ALTER FUNCTION %s OWNER TO postgres', fn);
        RAISE NOTICE '% now owned by postgres', fn;
    END LOOP;
END;
$$;

