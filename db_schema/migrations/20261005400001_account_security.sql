                    FROM public.posts p WHERE p.author_id = v_profile),
        'post_interactions', (SELECT coalesce(jsonb_agg(jsonb_build_object(
                                  'post_id', i.post_id, 'type', i.interaction_type,
                                  'emoji_id', i.emoji_id, 'emoji', i.custom_emoji_content,
