CREATE OR REPLACE FUNCTION public.normalize_recovery_code(p_code text)
RETURNS text
LANGUAGE sql
IMMUTABLE
SET search_path = pg_catalog, pg_temp
AS $$
    SELECT translate(upper(regexp_replace(coalesce(p_code, ''), '[^0-9A-Za-z]', '', 'g')), 'OIL', '011');
$$;

CREATE OR REPLACE FUNCTION public.hash_recovery_code(p_code text)
RETURNS text
LANGUAGE sql
IMMUTABLE
SET search_path = pg_catalog, public, pg_temp
AS $$
    SELECT encode(extensions.digest(convert_to(public.normalize_recovery_code(p_code), 'UTF8'), 'sha256'), 'hex');
$$;

REVOKE ALL ON FUNCTION public.normalize_recovery_code(text) FROM PUBLIC, anon, authenticated;
REVOKE ALL ON FUNCTION public.hash_recovery_code(text) FROM PUBLIC, anon, authenticated;

-- Owner key for new mfa_recovery_codes rows: auth uid where the table's foreign key points
-- at auth.users (production), profile id where it points at profiles (baseline).
CREATE OR REPLACE FUNCTION public.recovery_code_owner(p_auth_user_id uuid, p_profile_id uuid)
RETURNS uuid
LANGUAGE sql
STABLE
SET search_path = pg_catalog, public, pg_temp
AS $$
    SELECT CASE WHEN EXISTS (
               SELECT 1 FROM pg_constraint c
                WHERE c.conrelid = 'public.mfa_recovery_codes'::regclass
                  AND c.contype = 'f'
                  AND c.confrelid = 'auth.users'::regclass)
           THEN p_auth_user_id ELSE p_profile_id END;
$$;

REVOKE ALL ON FUNCTION public.recovery_code_owner(uuid, uuid) FROM PUBLIC, anon, authenticated;

-- Rows are keyed by profile id (baseline FK) or auth uid (production FK to auth.users);
-- local profiles carry id = auth_user_id, so both keys are matched.
CREATE OR REPLACE FUNCTION public.generate_mfa_recovery_codes()
RETURNS text[]
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = pg_catalog, public, pg_temp
AS $$
DECLARE
    c_alphabet constant text := '0123456789ABCDEFGHJKMNPQRSTVWXYZ';
    v_uid uuid := auth.uid();
    v_profile uuid := public.get_current_profile_id();
    v_batch uuid := gen_random_uuid();
    v_codes text[] := '{}';
    v_bytes bytea;
    v_code text;
    i integer;
    j integer;
BEGIN
    IF v_uid IS NULL OR v_profile IS NULL THEN
        RAISE EXCEPTION 'Authentication required' USING ERRCODE = '42501';
    END IF;
    IF NOT public.mfa_enabled_for(v_uid) THEN
        RAISE EXCEPTION 'mfa_not_enabled' USING ERRCODE = 'P0001';
    END IF;
    IF public.current_jwt_claims() ->> 'aal' IS DISTINCT FROM 'aal2'
       OR NOT public.session_step_up_fresh('totp', interval '10 minutes') THEN
        RAISE SQLSTATE 'PT403' USING
            MESSAGE = 'step_up_required',
            HINT = 'Verify an authenticator code first.';
    END IF;

    FOR i IN 1..10 LOOP
        v_bytes := extensions.gen_random_bytes(10);
        v_code := '';
        FOR j IN 0..9 LOOP
            -- 256 is a multiple of 32: the low five bits are uniform.
            v_code := v_code || substr(c_alphabet, (get_byte(v_bytes, j) & 31) + 1, 1);
        END LOOP;
        v_codes := v_codes || (substr(v_code, 1, 5) || '-' || substr(v_code, 6, 5));
    END LOOP;

    DELETE FROM public.mfa_recovery_codes r WHERE r.user_id IN (v_profile, v_uid);
    INSERT INTO public.mfa_recovery_codes (user_id, code_hash, batch_id)
    SELECT public.recovery_code_owner(v_uid, v_profile), public.hash_recovery_code(c), v_batch
      FROM unnest(v_codes) c;

    PERFORM public.record_security_notice(v_uid, 'recovery_codes_regenerated');
    RETURN v_codes;
END;
$$;

CREATE OR REPLACE FUNCTION public.get_mfa_recovery_status()
RETURNS jsonb
LANGUAGE plpgsql
STABLE
SECURITY DEFINER
SET search_path = pg_catalog, public, pg_temp
AS $$
DECLARE
    v_uid uuid := auth.uid();
    v_profile uuid := public.get_current_profile_id();
    v_total integer;
    v_remaining integer;
    v_generated timestamptz;
BEGIN
    IF v_uid IS NULL OR v_profile IS NULL THEN
        RAISE EXCEPTION 'Authentication required' USING ERRCODE = '42501';
    END IF;
    SELECT count(*), count(*) FILTER (WHERE r.used_at IS NULL), max(r.created_at)
      INTO v_total, v_remaining, v_generated
      FROM public.mfa_recovery_codes r
     WHERE r.user_id IN (v_profile, v_uid);
    RETURN jsonb_build_object(
        'mfa_enabled', public.mfa_enabled_for(v_uid),
        'total', v_total,
        'remaining', v_remaining,
        'generated_at', v_generated);
END;
$$;

-- Client-supplied codes, kept for released clients that generate at enrolment. Requires
-- aal2 when a factor is verified: an aal1 session must not be able to plant codes it can
-- then redeem.
CREATE OR REPLACE FUNCTION public.save_recovery_codes(p_user_id uuid, p_codes text[])
RETURNS void
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = pg_catalog, public, pg_temp
AS $$
DECLARE
    v_uid uuid := auth.uid();
    v_caller uuid := public.get_current_profile_id();
    v_batch uuid := gen_random_uuid();
    v_code text;
BEGIN
    IF v_uid IS NULL OR v_caller IS NULL THEN
        RAISE EXCEPTION 'Authentication required' USING ERRCODE = '42501';
    END IF;
    IF p_user_id IS DISTINCT FROM v_caller AND p_user_id IS DISTINCT FROM v_uid THEN
        RAISE EXCEPTION 'Permission denied: can only save your own recovery codes' USING ERRCODE = '42501';
    END IF;
    IF public.mfa_enabled_for(v_uid) AND public.current_jwt_claims() ->> 'aal' IS DISTINCT FROM 'aal2' THEN
        RAISE SQLSTATE 'PT403' USING MESSAGE = 'insufficient_aal';
    END IF;
    IF coalesce(array_length(p_codes, 1), 0) NOT BETWEEN 1 AND 20 THEN
        RAISE EXCEPTION 'Expected between 1 and 20 recovery codes' USING ERRCODE = '22023';
    END IF;
    FOREACH v_code IN ARRAY p_codes LOOP
        IF length(public.normalize_recovery_code(v_code)) NOT BETWEEN 8 AND 32 THEN
            RAISE EXCEPTION 'Recovery codes must be 8 to 32 letters or digits' USING ERRCODE = '22023';
        END IF;
    END LOOP;

    DELETE FROM public.mfa_recovery_codes r WHERE r.user_id IN (v_caller, v_uid);
    INSERT INTO public.mfa_recovery_codes (user_id, code_hash, batch_id)
    SELECT public.recovery_code_owner(v_uid, v_caller), public.hash_recovery_code(c), v_batch
      FROM unnest(p_codes) c;
END;
$$;

-- Marks a code used. Does not touch factors. Budgeted with redemption.
CREATE OR REPLACE FUNCTION public.verify_recovery_code(p_user_id uuid, p_code text)
RETURNS boolean
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = pg_catalog, public, pg_temp
AS $$
DECLARE
    v_uid uuid := auth.uid();
    v_profile uuid := public.get_current_profile_id();
    v_code_id uuid;
BEGIN
    IF v_uid IS NULL THEN
        RAISE EXCEPTION 'Unauthorized: verify_recovery_code requires an authenticated session'
            USING ERRCODE = '42501';
    END IF;
    IF p_user_id IS DISTINCT FROM v_uid THEN
        RAISE EXCEPTION 'Unauthorized: cannot verify recovery codes for another user'
            USING ERRCODE = '42501';
    END IF;

    PERFORM public.assert_security_attempt_budget(v_uid, 'recovery_code');

    UPDATE public.mfa_recovery_codes r
       SET used_at = now()
     WHERE r.id = (SELECT c.id FROM public.mfa_recovery_codes c
                    WHERE c.user_id IN (v_profile, v_uid)
                      AND c.code_hash = public.hash_recovery_code(p_code)
                      AND c.used_at IS NULL
                    LIMIT 1
                    FOR UPDATE SKIP LOCKED)
    RETURNING r.id INTO v_code_id;

    PERFORM public.record_security_attempt(v_uid, 'recovery_code', v_code_id IS NOT NULL);
    IF v_code_id IS NOT NULL THEN
        PERFORM public.record_security_notice(v_uid, 'recovery_code_used');
    END IF;
    RETURN v_code_id IS NOT NULL;
END;
$$;

-- Sign-in with a lost authenticator: consumes a code and removes the account's factors in
-- one transaction. Reachable below aal2 (enforce_request_assurance allows its path).
CREATE OR REPLACE FUNCTION public.redeem_recovery_code_and_disable_mfa(p_code text)
RETURNS boolean
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = pg_catalog, public, pg_temp
AS $$
DECLARE
    v_uid uuid := auth.uid();
    v_profile uuid := public.get_current_profile_id();
    v_code_id uuid;
BEGIN
    IF v_uid IS NULL THEN
        RAISE EXCEPTION 'Unauthorized: requires an authenticated session' USING ERRCODE = '42501';
    END IF;
    IF length(public.normalize_recovery_code(p_code)) < 8 THEN
        RETURN false;
    END IF;

    PERFORM public.assert_security_attempt_budget(v_uid, 'recovery_code');

    UPDATE public.mfa_recovery_codes r
       SET used_at = now()
     WHERE r.id = (SELECT c.id FROM public.mfa_recovery_codes c
                    WHERE c.user_id IN (v_profile, v_uid)
                      AND c.code_hash = public.hash_recovery_code(p_code)
                      AND c.used_at IS NULL
                    LIMIT 1
                    FOR UPDATE SKIP LOCKED)
    RETURNING r.id INTO v_code_id;

    PERFORM public.record_security_attempt(v_uid, 'recovery_code', v_code_id IS NOT NULL);
    IF v_code_id IS NULL THEN
        RETURN false;
    END IF;

    PERFORM set_config('harmony.mfa_disable_reason', 'recovery_code', true);
    IF to_regclass('auth.mfa_factors') IS NOT NULL THEN
        DELETE FROM auth.mfa_factors f WHERE f.user_id = v_uid;
    END IF;
    DELETE FROM public.mfa_recovery_codes r WHERE r.user_id IN (v_profile, v_uid);
    RETURN true;
END;
$$;

