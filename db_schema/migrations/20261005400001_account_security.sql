-- Re-entry of the current password before a password change. GoTrue's PUT /user takes no
-- current password, so this gates the settings form, not the API. Shares the password
-- budget with delete_my_account.
CREATE OR REPLACE FUNCTION public.verify_my_password(p_password text)
RETURNS boolean
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = pg_catalog, public, pg_temp
AS $$
DECLARE
    v_uid uuid := auth.uid();
    v_hash text;
    v_ok boolean;
BEGIN
    IF v_uid IS NULL THEN
        RAISE EXCEPTION 'Authentication required' USING ERRCODE = '42501';
    END IF;
    SELECT u.encrypted_password INTO v_hash FROM auth.users u WHERE u.id = v_uid;
    IF v_hash IS NULL OR v_hash NOT LIKE '$2%' THEN
        RAISE EXCEPTION 'no_password' USING ERRCODE = 'P0001';
    END IF;
    PERFORM public.assert_security_attempt_budget(v_uid, 'password');
    v_ok := extensions.crypt(coalesce(p_password, ''), v_hash) = v_hash;
    PERFORM public.record_security_attempt(v_uid, 'password', v_ok);
    RETURN v_ok;
END;
$$;

REVOKE ALL ON FUNCTION public.verify_my_password(text) FROM PUBLIC, anon, authenticated;
GRANT EXECUTE ON FUNCTION public.verify_my_password(text) TO authenticated;

