#!/usr/bin/env bash
# Ephemeral Postgres + GoTrue + PostgREST + storage stack for E2E runs. Credentials are
# generated into e2e/stack.env.
#
#   up      tear down, raise containers, build the schema from init/
#   seed    create the fixture (users via GoTrue, graph via PostgREST)
#   smoke   sign in and assert one RLS allow and one RLS deny
#   verify  up + seed + smoke
#   down    remove containers, volumes, network and stack.env
#   status  containers and port
#   logs    compose logs
#
# E2E_PROJECT and E2E_PORT name the compose project and gateway port, so stacks of separate
# checkouts run side by side. E2E_SUBNET, when set, is the compose network's subnet.
#
# Schema build mirrors scripts/run-db-tests.sh: scripts/test-db/supabase-compat.sql
# as supabase_admin, then init/init.sql as postgres. Added here: role passwords and
# e2e/jwt-claims-compat.sql.
#
# No realtime, postgres-meta, federation backend or Redis. The gateway answers 501 on
# the realtime and functions paths.
#
# The OIDC provider (dex) listens on E2E_IDP_PORT, default E2E_PORT + 2000 (e2e/specs/livekit.ts
# takes E2E_PORT + 1000 to + 1012), on a network of 198.18.0.0/15 (E2E_IDP_SUBNET, default one
# /24 per E2E_PORT modulo 512). Its config, CA and certificate are generated into e2e/idp/.
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
E2E="$ROOT/e2e"
PROJECT="${E2E_PROJECT:-hme2e}"
COMPOSE_FILE="$E2E/docker-compose.yml"
ENV_FILE="$E2E/stack.env"
FIXTURE_FILE="$E2E/fixture.json"

PORT="${E2E_PORT:-54480}"
BASE_URL="http://localhost:$PORT"

IDP_DIR="$E2E/idp"
IDP_PORT="${E2E_IDP_PORT:-$((PORT + 2000))}"
idp_net=$((PORT % 512))
IDP_SUBNET="${E2E_IDP_SUBNET:-198.$((18 + idp_net / 256)).$((idp_net % 256)).0/24}"
IDP_HOST="idp.e2e.test"
IDP_ISSUER="https://$IDP_HOST:$IDP_PORT/dex"

# Throwaway values; the database publishes no port.
DB_PASSWORD="e2e-local-postgres"
JWT_SECRET="e2e-local-jwt-secret-at-least-32-characters"
IDP_CLIENT_ID="harmony-e2e"
IDP_CLIENT_SECRET="e2e-idp-client-secret"
IDP_PASSWORD="e2e-idp-password-12345"
# bcrypt (cost 10) of IDP_PASSWORD.
IDP_PASSWORD_HASH='$2a$10$bHxt7zb62lwgA4jIKGqG5eoZkbH8AJYZY7nf1pD1UxwZ/ioCol.ee'
IDP_NEW_EMAIL="oidc-new@e2e.harmony.local"
IDP_LINK_EMAIL="oidc-link@e2e.harmony.local"
IDP_APART_EMAIL="oidc-apart@e2e.harmony.local"

log()  { printf '\033[36m==>\033[0m %s\n' "$*"; }
ok()   { printf '\033[32mok \033[0m %s\n' "$*"; }
err()  { printf '\033[31mFAIL\033[0m %s\n' "$*" >&2; }
die()  { err "$*"; exit 1; }

compose() {
  local args=(-p "$PROJECT" -f "$COMPOSE_FILE")
  # E2E_SUBNET pins the network's subnet; Docker's default address pools run out on a
  # host with many networks.
  [ -n "${E2E_SUBNET:-}" ] && args+=(-f "$E2E/docker-compose.subnet.yml")
  [ -f "$ENV_FILE" ] && args+=(--env-file "$ENV_FILE")
  docker compose "${args[@]}" "$@"
}

# HS256 JWT. Mirrors sign_jwt in self-host/configure.sh.
sign_jwt() {
  local role="$1" secret="$2" now exp header payload body sig
  now=$(date +%s); exp=$((now + 86400))
  header=$(printf '{"alg":"HS256","typ":"JWT"}' | openssl base64 -e -A | tr '+/' '-_' | tr -d '=')
  payload=$(printf '{"role":"%s","iss":"supabase","iat":%d,"exp":%d}' "$role" "$now" "$exp" |
    openssl base64 -e -A | tr '+/' '-_' | tr -d '=')
  body="${header}.${payload}"
  sig=$(printf '%s' "$body" | openssl dgst -sha256 -hmac "$secret" -binary |
    openssl base64 -e -A | tr '+/' '-_' | tr -d '=')
  printf '%s.%s' "$body" "$sig"
}

write_env() {
  local anon service
  anon=$(sign_jwt anon "$JWT_SECRET")
  service=$(sign_jwt service_role "$JWT_SECRET")
  cat >"$ENV_FILE" <<EOF
# Generated by e2e/stack.sh. Recreated on \`up\`, removed by \`down\`.
E2E_PORT=$PORT
E2E_DB_PASSWORD=$DB_PASSWORD
E2E_JWT_SECRET=$JWT_SECRET

E2E_SUPABASE_URL=$BASE_URL
E2E_SUPABASE_ANON_KEY=$anon
E2E_SUPABASE_SERVICE_ROLE_KEY=$service

TEST_SUPABASE_URL=$BASE_URL
TEST_SUPABASE_ANON_KEY=$anon
TEST_SUPABASE_SERVICE_ROLE_KEY=$service
VITE_SUPABASE_URL=$BASE_URL
VITE_SUPABASE_ANON_KEY=$anon

# Bare usernames resolve against VITE_DOMAIN; profiles.domain and instance_config
# default to 'localhost'. Unset, lookups use domain=undefined and find no profile.
VITE_DOMAIN=localhost

# The sign-in footer and Settings link here (auth-landing.spec.ts).
VITE_STATUS_URL=https://status.example.test

# OIDC provider (dex); compose reads the port and subnet.
E2E_IDP_PORT=$IDP_PORT
E2E_IDP_SUBNET=$IDP_SUBNET
E2E_IDP_HOST=$IDP_HOST
E2E_IDP_ISSUER=$IDP_ISSUER
E2E_IDP_CLIENT_ID=$IDP_CLIENT_ID
E2E_IDP_CLIENT_SECRET=$IDP_CLIENT_SECRET
E2E_IDP_PASSWORD=$IDP_PASSWORD
E2E_IDP_NEW_EMAIL=$IDP_NEW_EMAIL
E2E_IDP_LINK_EMAIL=$IDP_LINK_EMAIL
E2E_IDP_APART_EMAIL=$IDP_APART_EMAIL
EOF
  ok "wrote e2e/stack.env"
}

# dex config, a throwaway CA and the certificate for IDP_HOST. dex runs as uid 1001, so
# the key is world-readable.
write_idp() {
  rm -rf "$IDP_DIR"
  mkdir -p "$IDP_DIR"
  openssl req -x509 -newkey rsa:2048 -nodes -days 2 -subj "/CN=Harmony E2E CA" \
    -keyout "$IDP_DIR/ca.key" -out "$IDP_DIR/ca.pem" >/dev/null 2>&1 ||
    die "openssl could not create the IdP CA"
  openssl req -newkey rsa:2048 -nodes -subj "/CN=$IDP_HOST" \
    -keyout "$IDP_DIR/idp.key" -out "$IDP_DIR/idp.csr" >/dev/null 2>&1 ||
    die "openssl could not create the IdP key"
  printf 'subjectAltName=DNS:%s\nextendedKeyUsage=serverAuth\n' "$IDP_HOST" >"$IDP_DIR/idp.ext"
  openssl x509 -req -in "$IDP_DIR/idp.csr" -CA "$IDP_DIR/ca.pem" -CAkey "$IDP_DIR/ca.key" \
    -CAcreateserial -days 2 -extfile "$IDP_DIR/idp.ext" -out "$IDP_DIR/idp.pem" >/dev/null 2>&1 ||
    die "openssl could not sign the IdP certificate"
  rm -f "$IDP_DIR/idp.csr" "$IDP_DIR/idp.ext" "$IDP_DIR/ca.key" "$IDP_DIR/ca.srl"
  chmod 644 "$IDP_DIR/idp.key"

  cat >"$IDP_DIR/config.yaml" <<EOF
# Generated by e2e/stack.sh.
issuer: $IDP_ISSUER
storage:
  type: memory
web:
  https: 0.0.0.0:$IDP_PORT
  tlsCert: /etc/dex/idp.pem
  tlsKey: /etc/dex/idp.key
oauth2:
  skipApprovalScreen: true
enablePasswordDB: true
staticClients:
  - id: $IDP_CLIENT_ID
    name: Harmony E2E
    secret: $IDP_CLIENT_SECRET
    redirectURIs:
      - $BASE_URL/auth/v1/callback
staticPasswords:
  - email: $IDP_NEW_EMAIL
    hash: "$IDP_PASSWORD_HASH"
    username: Ada Oidc
    userID: 0b0d1d6e-0000-4000-8000-000000000001
  - email: $IDP_LINK_EMAIL
    hash: "$IDP_PASSWORD_HASH"
    username: Linked Oidc
    userID: 0b0d1d6e-0000-4000-8000-000000000002
  - email: $IDP_APART_EMAIL
    hash: "$IDP_PASSWORD_HASH"
    username: Apart Oidc
    userID: 0b0d1d6e-0000-4000-8000-000000000003
EOF
  ok "wrote e2e/idp/ (issuer $IDP_ISSUER)"
}

db_cid() { compose ps -q db; }

psql_admin() { # superuser; owns the auth and realtime schemas
  docker exec -i "$(db_cid)" psql -U supabase_admin -h 127.0.0.1 -d postgres "$@"
}
psql_postgres() {
  docker exec -i "$(db_cid)" psql -U postgres -d postgres "$@"
}

wait_http() { # wait_http <url> <expected-status-regex> <what> [tries]
  local url="$1" want="$2" what="$3" tries="${4:-90}" code
  for _ in $(seq 1 "$tries"); do
    code=$(curl -s -o /dev/null -w '%{http_code}' "$url" || true)
    [[ "$code" =~ $want ]] && { ok "$what ($code)"; return 0; }
    sleep 1
  done
  err "$what never answered (last status ${code:-none})"
  return 1
}

cmd_up() {
  command -v docker >/dev/null || die "docker is required"
  command -v openssl >/dev/null || die "openssl is required"
  command -v curl >/dev/null || die "curl is required"

  # init.sql does not run twice over itself; start from an empty database.
  cmd_down

  write_env
  write_idp

  log "starting postgres"
  compose up -d db
  local cid; cid="$(db_cid)"
  # Five consecutive answers, as in scripts/run-db-tests.sh: the image restarts
  # the server partway through init.
  local streak=0
  for _ in $(seq 1 120); do
    if docker exec "$cid" psql -U postgres -h 127.0.0.1 -d postgres -tAc 'select 1' >/dev/null 2>&1; then
      streak=$((streak + 1)); [ "$streak" -ge 5 ] && break
    else streak=0; fi
    sleep 1
  done
  [ "$streak" -ge 5 ] || { docker logs "$cid" | tail -20; die "postgres never stabilised"; }
  ok "postgres up"

  # GoTrue and PostgREST connect over TCP as roles the image leaves without a
  # password.
  log "setting role passwords"
  psql_admin -q -v ON_ERROR_STOP=1 -v pw="$DB_PASSWORD" <<'SQL'
\set qpw '''' :pw ''''
ALTER ROLE authenticator WITH LOGIN PASSWORD :qpw;
ALTER ROLE supabase_auth_admin WITH LOGIN PASSWORD :qpw;
ALTER ROLE supabase_storage_admin WITH LOGIN PASSWORD :qpw;
ALTER ROLE postgres WITH PASSWORD :qpw;
SQL

  # storage-api migrates the storage schema on start; the schema build after it
  # adds policies and buckets to the finished tables.
  log "starting storage"
  compose up -d storage imgproxy
  local scid; scid="$(compose ps -q storage)"
  for _ in $(seq 1 90); do
    docker exec "$scid" wget -q -O /dev/null http://127.0.0.1:5000/status 2>/dev/null && break
    sleep 1
  done
  docker exec "$scid" wget -q -O /dev/null http://127.0.0.1:5000/status 2>/dev/null ||
    { docker logs "$scid" 2>&1 | tail -20; die "storage never answered /status"; }
  ok "storage up"

  log "starting auth, rest and gateway"
  compose up -d
  wait_http "$BASE_URL/health" '^200$' "gateway"
  # GoTrue answers /health only once its auth-schema migrations have finished.
  wait_http "$BASE_URL/auth/v1/health" '^200$' "gotrue"

  build_schema

  log "reloading PostgREST schema cache"
  psql_postgres -q -c "NOTIFY pgrst, 'reload schema'"
  # PostgREST answers 401 on the root without a key.
  wait_http "$BASE_URL/rest/v1/" '^(200|400|401)$' "postgrest"

  ok "stack up on $BASE_URL"
}

build_schema() {
  local cid; cid="$(db_cid)"

  log "building schema from init/"
  docker exec "$cid" rm -rf /db_schema
  docker cp "$ROOT/db_schema" "$cid:/db_schema" >/dev/null
  docker cp "$ROOT/scripts/test-db/supabase-compat.sql" "$cid:/compat.sql" >/dev/null
  docker cp "$E2E/jwt-claims-compat.sql" "$cid:/jwt-claims-compat.sql" >/dev/null

  # As in scripts/run-db-tests.sh: the realtime schema belongs to supabase_admin,
  # and postgres is not superuser in this image.
  docker exec "$cid" psql -U supabase_admin -h 127.0.0.1 -d postgres -q -f /compat.sql 2>&1 |
    grep -v 'already exists, skipping' || true

  docker exec "$cid" psql -U postgres -d postgres -tAc \
    "SELECT 1 FROM pg_proc p JOIN pg_namespace n ON n.oid=p.pronamespace
      WHERE n.nspname='realtime' AND p.proname='send'" | grep -q 1 ||
    die "realtime.send stub missing after compat; broadcast triggers will fail"

  docker exec "$cid" psql -U supabase_admin -h 127.0.0.1 -d postgres -q \
    -v ON_ERROR_STOP=1 -f /jwt-claims-compat.sql

  # init.sql reports every skipped policy and index at NOTICE.
  PGOPTIONS='-c client_min_messages=warning' \
    "$ROOT/scripts/test-db/load-schema.sh" "$cid"

  # A null auth.uid() makes every later RLS deny look deliberate.
  local uid
  uid=$(docker exec "$cid" psql -U postgres -d postgres -tAc \
    "SELECT set_config('request.jwt.claims','{\"sub\":\"aaaaaaaa-0000-0000-0000-000000000001\"}',false) IS NOT NULL
       AND auth.uid() = 'aaaaaaaa-0000-0000-0000-000000000001'::uuid")
  [ "$uid" = "t" ] || die "auth.uid() does not read request.jwt.claims"
  ok "schema built; auth.uid() reads request.jwt.claims"
}

require_env() {
  [ -f "$ENV_FILE" ] || die "e2e/stack.env missing - run: npm run e2e:up"
}

cmd_seed() {
  require_env
  log "seeding fixture"
  node "$E2E/seed.mjs"
}

cmd_smoke() {
  require_env
  [ -f "$FIXTURE_FILE" ] || die "e2e/fixture.json missing - run: npm run e2e:seed"
  node "$E2E/smoke.mjs"
}

cmd_down() {
  log "tearing down"
  compose down -v --remove-orphans --timeout 5 >/dev/null 2>&1 || true

  # Containers compose no longer accounts for still carry the project label.
  local leftovers
  leftovers=$(docker ps -aq --filter "label=com.docker.compose.project=$PROJECT" || true)
  [ -n "$leftovers" ] && docker rm -f $leftovers >/dev/null 2>&1 || true
  leftovers=$(docker volume ls -q --filter "label=com.docker.compose.project=$PROJECT" || true)
  [ -n "$leftovers" ] && docker volume rm -f $leftovers >/dev/null 2>&1 || true
  leftovers=$(docker network ls -q --filter "label=com.docker.compose.project=$PROJECT" || true)
  [ -n "$leftovers" ] && docker network rm $leftovers >/dev/null 2>&1 || true

  rm -f "$ENV_FILE" "$FIXTURE_FILE"
  rm -rf "$IDP_DIR"
  ok "stack down"
}

cmd_status() {
  printf 'project %s, url %s\n' "$PROJECT" "$BASE_URL"
  docker ps -a --filter "label=com.docker.compose.project=$PROJECT" \
    --format 'table {{.Names}}\t{{.Image}}\t{{.Status}}'
  [ -f "$ENV_FILE" ] && printf 'stack.env present\n' || printf 'stack.env absent\n'
  [ -f "$FIXTURE_FILE" ] && printf 'fixture.json present\n' || printf 'fixture.json absent\n'
}

case "${1:-}" in
  up)     cmd_up ;;
  seed)   cmd_seed ;;
  smoke)  cmd_smoke ;;
  verify) cmd_up; cmd_seed; cmd_smoke ;;
  down)   cmd_down ;;
  status) cmd_status ;;
  logs)   shift; compose logs "$@" ;;
  *)      die "usage: stack.sh {up|seed|smoke|verify|down|status|logs}" ;;
esac
