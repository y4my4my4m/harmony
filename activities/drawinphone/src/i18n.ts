const TABLES: Record<string, Table> = { en, es, fr, de, ja, ko, zh }

export const LOCALES = Object.keys(TABLES)

export function translator(locale: string): (key: Key, vars?: Record<string, string | number>) => string {
  const table = TABLES[locale.slice(0, 2).toLowerCase()] ?? en
  return (key, vars) => {
    let text = table[key] ?? en[key]
    if (vars) for (const [name, value] of Object.entries(vars)) text = text.split(`{${name}}`).join(String(value))
    return text
  }
}

/** Keys a locale lacks; empty for every shipped locale (tested). */
export function missingKeys(locale: string): Key[] {
  const table = TABLES[locale] ?? {}
  return (Object.keys(en) as Key[]).filter((key) => !(key in table))
}
